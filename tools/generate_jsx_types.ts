function svgAttributeType(attribute: string): string {
  const override = svgTypeOverrides.get(attribute);
  if (override) return override;
  if (numericSvgAttributes.has(attribute)) return "SVGNumberAttribute";
  return "StringAttribute";
}

function renderLiteralUnion(name: string, values: readonly string[]): string {
  return [
    `type ${name} =`,
    ...values.map((value, index) =>
      `  | ${quote(value)}${index === values.length - 1 ? ";" : ""}`
    ),
    "",
  ].join("\n");
}

function propertyName(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : quote(name);
}

function pascalCase(name: string): string {
  return name[0].toUpperCase() + name.slice(1);
}

function quote(value: string): string {
  return JSON.stringify(value);
}

function compareStrings(left: string, right: string): number {
  return left < right ? -1 : left > right ? 1 : 0;
}

