function htmlAttributeType(element: string, attribute: string): string {
  const override = htmlTypeOverrides.get(`${element}.${attribute}`) ??
    htmlTypeOverrides.get(`*.${attribute}`);
  if (override) return override;
  if (booleanHtmlAttributes.has(attribute)) return "BooleanAttribute";
  if (numericHtmlAttributes.has(attribute)) return "NumberAttribute";
  if (attribute === "crossorigin") return "Omissible<CrossOrigin>";
  if (attribute === "fetchpriority") return "Omissible<FetchPriority>";
  if (attribute === "referrerpolicy") return "Omissible<ReferrerPolicy>";
  if (attribute === "value") return "ScalarAttribute";
  if (["max", "min", "step"].includes(attribute)) return "ScalarAttribute";
  return "StringAttribute";
}

function ariaAttributeType(attribute: string): string {
  if (attribute === "role") return "AriaRoleAttribute";
  if (
    [
      "aria-atomic",
      "aria-busy",
      "aria-disabled",
      "aria-modal",
      "aria-multiline",
      "aria-multiselectable",
      "aria-readonly",
      "aria-required",
    ].includes(attribute)
  ) return "BooleanishAttribute";
  if (["aria-checked", "aria-pressed"].includes(attribute)) {
    return 'Omissible<"false" | "mixed" | "true" | "undefined">';
  }
  if (["aria-expanded", "aria-hidden", "aria-selected"].includes(attribute)) {
    return 'Omissible<"false" | "true" | "undefined">';
  }
  if (
    [
      "aria-colcount",
      "aria-colindex",
      "aria-colspan",
      "aria-level",
      "aria-posinset",
      "aria-rowcount",
      "aria-rowindex",
      "aria-rowspan",
      "aria-setsize",
      "aria-valuemax",
      "aria-valuemin",
      "aria-valuenow",
    ].includes(attribute)
  ) return "NumberAttribute";

  const enumerated = new Map<string, readonly string[]>([
    ["aria-autocomplete", ["both", "inline", "list", "none"]],
    ["aria-invalid", ["false", "grammar", "spelling", "true"]],
    ["aria-live", ["assertive", "off", "polite"]],
    ["aria-orientation", ["horizontal", "undefined", "vertical"]],
    ["aria-sort", ["ascending", "descending", "none", "other"]],
  ]);
  if (attribute === "aria-current") return "Omissible<AriaCurrent>";
  if (attribute === "aria-haspopup") return "Omissible<AriaHasPopup>";
  const values = enumerated.get(attribute);
  if (values) return `Omissible<${values.map(quote).join(" | ")}>`;
  if (attribute === "aria-relevant") {
    return "Omissible<AriaRelevant>";
  }
  if (!attribute.startsWith("aria-")) {
    throw new Error(`Unknown ARIA attribute ${attribute}.`);
  }
  return "StringAttribute";
}

